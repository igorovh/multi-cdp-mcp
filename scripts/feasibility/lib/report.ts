import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

export type StepStatus = "pass" | "fail" | "skip" | "warn";

export interface StepResult {
  name: string;
  status: StepStatus;
  detail: string;
  durationMs: number;
}

export interface ExtensionObservation {
  environmentId: string;
  name: string;
  id: string;
  enabled: boolean | null;
}

export interface UrlObservation {
  environmentId: string;
  url: string;
  finalUrl: string;
  status: "loaded" | "error";
  detail: string;
}

export interface ReportData {
  startedAt: string;
  versions: Record<string, string>;
  connectionMode: string;
  steps: StepResult[];
  extensions: ExtensionObservation[];
  urls: UrlObservation[];
  notes: string[];
}

const STATUS_LABEL: Record<StepStatus, string> = {
  pass: "PASS",
  fail: "FAIL",
  skip: "SKIP",
  warn: "WARN",
};

function table(header: string[], rows: string[][]): string {
  if (rows.length === 0) return "_No data recorded._\n";
  const lines = [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ];
  return `${lines.join("\n")}\n`;
}

export function renderReport(data: ReportData): string {
  const sections: string[] = [];

  sections.push("# Brave Profile Feasibility Report\n");
  sections.push(
    "Generated by `scripts/feasibility/run.ts`. Records step outcomes only — " +
      "no cookies, tokens, or page contents.\n",
  );
  sections.push(`- Started: ${data.startedAt}`);
  sections.push(`- Connection mode used: ${data.connectionMode}\n`);

  sections.push("## Versions\n");
  sections.push(
    table(
      ["Component", "Version"],
      Object.entries(data.versions).map(([key, value]) => [key, value]),
    ),
  );

  sections.push("## Steps\n");
  sections.push(
    table(
      ["Step", "Result", "Duration", "Detail"],
      data.steps.map((step) => [
        step.name,
        STATUS_LABEL[step.status],
        `${(step.durationMs / 1000).toFixed(1)}s`,
        step.detail.replaceAll("|", "\\|"),
      ]),
    ),
  );

  sections.push("## Extensions\n");
  sections.push(
    table(
      ["Environment", "Extension", "ID", "Enabled"],
      data.extensions.map((extension) => [
        extension.environmentId,
        extension.name.replaceAll("|", "\\|"),
        extension.id,
        extension.enabled === null ? "unknown" : extension.enabled ? "yes" : "no",
      ]),
    ),
  );
  sections.push(
    "\nPresence in this table proves the extension is installed, not that it executes " +
      "on a page. Confirm behaviour manually.\n",
  );

  sections.push("## URLs\n");
  sections.push(
    table(
      ["Environment", "Requested", "Final URL", "Result", "Detail"],
      data.urls.map((url) => [
        url.environmentId,
        url.url,
        url.finalUrl,
        url.status,
        url.detail.replaceAll("|", "\\|"),
      ]),
    ),
  );
  sections.push(
    "\nA loaded page is not proof of a retained login. Check the sign-in state " +
      "yourself in each browser window.\n",
  );

  if (data.notes.length > 0) {
    sections.push("## Notes\n");
    sections.push(data.notes.map((note) => `- ${note}`).join("\n"));
    sections.push("");
  }

  return sections.join("\n");
}

export async function writeReport(path: string, data: ReportData): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, renderReport(data), "utf8");
}
